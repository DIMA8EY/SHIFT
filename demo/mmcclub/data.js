/* Псевдослучайно, но стабильно: один и тот же день всегда выглядит одинаково */
function slotIsBusy(centerId, dateISO, time) {
  const key = centerId + '|' + dateISO + '|' + time;
  let h = 2166136261;                                   // FNV-1a: ровное распределение
  for (let i = 0; i < key.length; i++) {
    h ^= key.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  h = (h ^ (h >>> 15)) >>> 0;
  return h % 100 < 35;                                  // около трети слотов занято
}
